#!/usr/bin/env python3
"""Convert the approved 4x4 gecko sprite sheet to a shared-palette 3DO animation.

Requires ImageMagick. This is an offline build step; the console never reads PNGs.
"""
from pathlib import Path
import hashlib
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def main():
    source = ROOT / "assets/channel-gecko-source.png"
    magick = shutil.which("magick") or shutil.which("convert")
    if not magick:
        raise SystemExit("ImageMagick is required")
    # A single palette prevents color flicker between frames. Reserve index 0
    # for transparency and index 1 for an opaque menu-colored ground, so every
    # new frame erases the last without another fill or a background snapshot.
    raw = subprocess.check_output(
        [
            magick,
            str(source),
            "-resize",
            "128x128!",
            "-alpha",
            "off",
            "-colors",
            "14",
            "-depth",
            "8",
            "rgb:-",
        ]
    )
    assert len(raw) == 128 * 128 * 3
    colors = [tuple(raw[i : i + 3]) for i in range(0, len(raw), 3)]
    foreground = sorted({c for c in colors if max(c) >= 48})
    assert len(foreground) <= 14
    palette = [0, 0x0843] + [
        ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3) for r, g, b in foreground
    ]
    indices = {c: i + 2 for i, c in enumerate(foreground)}
    frames = []
    for frame in range(16):
        pixels = []
        for y in range(32):
            for x in range(32):
                c = colors[(frame // 4 * 32 + y) * 128 + frame % 4 * 32 + x]
                pixels.append(indices.get(c, 1))
        frames.append(bytes((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2)))
    header = [
        "/* Generated by tools/prepare-channel-gecko.py; do not edit.",
        " * Source SHA256: " + hashlib.sha256(source.read_bytes()).hexdigest() + " */",
        "#ifndef CHANNEL_GECKO_DATA_H",
        "#define CHANNEL_GECKO_DATA_H",
        "#define CHANNEL_GECKO_FRAMES 16",
        "#define CHANNEL_GECKO_SIZE 32",
        "#define CHANNEL_GECKO_FRAME_MS 20UL",
        "static const unsigned short channel_gecko_palette[32] = {",
        "    " + ", ".join("0x%04x" % c for c in palette + [0] * (32 - len(palette))),
        "};",
        "static const unsigned char channel_gecko_pixels[16][512] = {",
    ]
    for pixels in frames:
        header.append("    {")
        for offset in range(0, len(pixels), 16):
            header.append(
                "        " + ",".join("0x%02x" % b for b in pixels[offset : offset + 16]) + ","
            )
        header.append("    },")
    header.extend(["};", "#endif", ""])
    (ROOT / "src/channel_gecko_data.h").write_text("\n".join(header))
    # Reconstruct the console's palette/indices for an exact-color preview.
    preview = bytearray(128 * 128 * 3)
    for frame, pixels in enumerate(frames):
        for y in range(32):
            for x in range(32):
                packed = pixels[y * 16 + x // 2]
                index = (packed >> (4 if x % 2 == 0 else 0)) & 15
                value = palette[index]
                offset = ((frame // 4 * 32 + y) * 128 + frame % 4 * 32 + x) * 3
                preview[offset : offset + 3] = bytes(
                    ((value >> shift) & 31) * 255 // 31 for shift in (10, 5, 0)
                )
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build/channel-gecko-native.ppm").write_bytes(b"P6\n128 128\n255\n" + preview)
    print("Gecko animation: 16 x 32x32 coded 4-bit frames; 8192 bytes + 64-byte shared palette")


if __name__ == "__main__":
    main()
