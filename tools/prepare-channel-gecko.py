#!/usr/bin/env python3
"""Convert the approved 4x4 gecko sprite sheet to a shared-palette 3DO animation.

Requires ImageMagick. This is an offline build step; the console never reads PNGs.

The sheet (assets/channel-gecko-source.png) holds 16 frames in a 4x4 grid.
It is scaled to 128x128 (32x32 frames) and reduced to 14 colors, then
written as src/channel_gecko_data.h: one shared palette of 15-bit colors,
and each frame as 4-bit palette indices, two pixels a byte. A preview of
exactly what the console will show is written to
build/channel-gecko-native.ppm.
"""
from pathlib import Path
import hashlib
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent.parent

FRAMES = 16
FRAMES_ACROSS = 4
FRAME_SIZE = 32
SHEET_SIZE = FRAME_SIZE * FRAMES_ACROSS

# Palette index 0 is transparent; index 1 is the menu's background color
# (dark blue-gray as 15-bit RGB), drawn under the gecko.
TRANSPARENT = 0
GROUND = 1
GROUND_COLOR = 0x0843
FIRST_COLOR = 2

# Darker pixels than this (in every channel) are background, not gecko.
FOREGROUND_THRESHOLD = 48


def to_rgb555(red, green, blue):
    """An 8-bit RGB color as the 3DO's 15-bit color."""
    return ((red >> 3) << 10) | ((green >> 3) << 5) | (blue >> 3)


def sheet_pixel(colors, frame, x, y):
    """The color at (x, y) in a frame of the sheet."""
    row = frame // FRAMES_ACROSS * FRAME_SIZE + y
    column = frame % FRAMES_ACROSS * FRAME_SIZE + x
    return colors[row * SHEET_SIZE + column]


def read_sheet(source):
    """The sheet scaled and reduced to 14 colors, as a list of RGB tuples."""
    magick = shutil.which("magick") or shutil.which("convert")
    if not magick:
        raise SystemExit("ImageMagick is required")
    raw = subprocess.check_output(
        [magick, str(source), "-resize", f"{SHEET_SIZE}x{SHEET_SIZE}!", "-alpha", "off"]
        + ["-colors", "14", "-depth", "8", "rgb:-"]
    )
    assert len(raw) == SHEET_SIZE * SHEET_SIZE * 3
    return [tuple(raw[i : i + 3]) for i in range(0, len(raw), 3)]


def encode_frames(colors):
    """The shared palette and each frame's packed 4-bit indices."""
    # A single palette prevents color flicker between frames. Reserve index 0
    # for transparency and index 1 for an opaque menu-colored ground, so every
    # new frame erases the last without another fill or a background snapshot.
    foreground = sorted({color for color in colors if max(color) >= FOREGROUND_THRESHOLD})
    assert len(foreground) <= 14
    palette = [TRANSPARENT, GROUND_COLOR] + [to_rgb555(*color) for color in foreground]
    indices = {color: index + FIRST_COLOR for index, color in enumerate(foreground)}

    frames = []
    for frame in range(FRAMES):
        pixels = [
            indices.get(sheet_pixel(colors, frame, x, y), GROUND)
            for y in range(FRAME_SIZE)
            for x in range(FRAME_SIZE)
        ]
        packed = bytes((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2))
        frames.append(packed)
    return palette, frames


def header_text(source, palette, frames):
    """src/channel_gecko_data.h: the palette (padded to 32 entries) and frames."""
    padded = palette + [0] * (32 - len(palette))
    lines = [
        "/* Generated by tools/prepare-channel-gecko.py; do not edit.",
        " * Source SHA256: " + hashlib.sha256(source.read_bytes()).hexdigest() + " */",
        "#ifndef CHANNEL_GECKO_DATA_H",
        "#define CHANNEL_GECKO_DATA_H",
        "#define CHANNEL_GECKO_FRAMES 16",
        "#define CHANNEL_GECKO_SIZE 32",
        "#define CHANNEL_GECKO_FRAME_MS 20UL",
        "static const unsigned short channel_gecko_palette[32] = {",
        "    " + ", ".join("0x%04x" % color for color in padded),
        "};",
        "static const unsigned char channel_gecko_pixels[16][512] = {",
    ]
    for pixels in frames:
        lines.append("    {")
        for offset in range(0, len(pixels), 16):
            row = ",".join("0x%02x" % byte for byte in pixels[offset : offset + 16])
            lines.append("        " + row + ",")
        lines.append("    },")
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def preview_image(palette, frames):
    """The sheet rebuilt from the palette and indices, as the console shows it (PPM)."""
    preview = bytearray(SHEET_SIZE * SHEET_SIZE * 3)
    for frame, pixels in enumerate(frames):
        for y in range(FRAME_SIZE):
            for x in range(FRAME_SIZE):
                packed = pixels[y * (FRAME_SIZE // 2) + x // 2]
                index = (packed >> (4 if x % 2 == 0 else 0)) & 15
                color = palette[index]
                row = frame // FRAMES_ACROSS * FRAME_SIZE + y
                column = frame % FRAMES_ACROSS * FRAME_SIZE + x
                offset = (row * SHEET_SIZE + column) * 3
                preview[offset : offset + 3] = bytes(
                    ((color >> shift) & 31) * 255 // 31 for shift in (10, 5, 0)
                )
    return b"P6\n128 128\n255\n" + preview


def main():
    source = ROOT / "assets/channel-gecko-source.png"
    palette, frames = encode_frames(read_sheet(source))
    (ROOT / "src/channel_gecko_data.h").write_text(header_text(source, palette, frames))
    # Reconstruct the console's palette/indices for an exact-color preview.
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build/channel-gecko-native.ppm").write_bytes(preview_image(palette, frames))
    print("Gecko animation: 16 x 32x32 coded 4-bit frames; 8192 bytes + 64-byte shared palette")


if __name__ == "__main__":
    main()
