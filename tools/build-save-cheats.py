#!/usr/bin/env python3
"""Validate the shared, source-verified save database and generate its C tables."""
import argparse
import json
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate(db):
    assert db['version'] == 1 and 1 <= len(db['profiles']) <= 128
    out = ['/* Generated by tools/build-save-cheats.py; edit data/save-cheats.json. */']
    ids = set()
    for i, p in enumerate(db['profiles']):
        assert p['id'] not in ids
        ids.add(p['id'])
        assert p['encoding'] == 'u32be' and p['checksum']['algorithm'] == 'sum32be'
        assert 8 <= p['size'] <= 32768 and p['size'] % 4 == 0
        assert p['checksum']['offset'] == p['size'] - 4
        assert p['source'].startswith('https://') and p['notes']
        for label in [p['game'], p['filename'], *[f['label'] for f in p['fields']], *[x['label'] for x in p['presets']]]:
            assert label and label.isascii() and all(32 <= ord(c) < 127 for c in label)
        assert len(p['filename']) <= 31 and not any(c in p['filename'] for c in '/\\:')
        assert 0 <= p['signature']['offset'] < p['checksum']['offset'] and p['signature']['offset'] % 4 == 0
        assert 0 <= p['signature']['value'] <= 0xffffffff and 0 <= p['checksum']['seed'] <= 0xffffffff
        offsets = {p['signature']['offset'], p['checksum']['offset']}
        assert 1 <= len(p['fields']) <= 32 and 1 <= len(p['presets']) <= 32
        assert len(p['id']) <= 63 and len(p['game']) <= 31
        out.append(f'static const SaveCheatField cheat_fields_{i}[] = {{')
        for f in p['fields']:
            assert 0 <= f['offset'] < p['checksum']['offset'] and f['offset'] % 4 == 0 and f['offset'] not in offsets
            offsets.add(f['offset'])
            assert 0 <= f['min'] <= f['max'] <= 0xffffffff and len(f['label']) <= 25
            out.append(f'    {{{json.dumps(f["label"])},{f["offset"]},{f["min"]}UL,{f["max"]}UL}},')
        out.append('};')
        out.append(f'static const SaveCheatPreset cheat_presets_{i}[] = {{')
        for x in p['presets']:
            assert 0 <= x['field'] < len(p['fields']) and len(x['label']) <= 34
            f = p['fields'][x['field']]
            assert f['min'] <= x['value'] <= f['max']
            out.append(f'    {{{json.dumps(x["label"])},{x["field"]},{x["value"]}UL}},')
        out.append('};')
    out.append('static const SaveCheatProfile cheat_profiles[] = {')
    for i, p in enumerate(db['profiles']):
        out.append('    {%s,%s,%s,%d,%d,%dUL,%d,%dUL,cheat_fields_%d,%d,cheat_presets_%d,%d},' % (
            json.dumps(p['id']), json.dumps(p['game']), json.dumps(p['filename']), p['size'],
            p['signature']['offset'], p['signature']['value'], p['checksum']['offset'], p['checksum']['seed'],
            i, len(p['fields']), i, len(p['presets'])))
    out.append('};')
    return '\n'.join(out) + '\n'

def binary(db):
    generate(db)
    def text(value, size):
        b = value.encode('ascii')
        assert len(b) < size
        return b + bytes(size - len(b))
    payload = bytearray()
    for p in db['profiles']:
        payload += struct.pack('>8I', 160 + 40*len(p['fields']) + 48*len(p['presets']), p['size'], p['signature']['offset'], p['signature']['value'], p['checksum']['offset'], p['checksum']['seed'], len(p['fields']), len(p['presets']))
        payload += text(p['id'],64)+text(p['game'],32)+text(p['filename'],32)
        for f in p['fields']:
            payload += text(f['label'],28)+struct.pack('>3I',f['offset'],f['min'],f['max'])
        for x in p['presets']:
            payload += text(x['label'],36)+struct.pack('>3I',x['field'],x['value'],0)
    assert len(payload)+24 <= 65536
    return b'OM3DCHT1'+struct.pack('>4I',24+len(payload),len(db['profiles']),zlib.crc32(payload),0)+payload

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--binary', type=Path, help='Export the compact console database')
    parser.add_argument('--source', type=Path, default=ROOT/'data/save-cheats.json')
    args = parser.parse_args()
    if args.source != ROOT/'data/save-cheats.json' and not args.binary:
        parser.error('--source requires --binary; custom exports do not replace the bundled fallback')
    db = json.loads(args.source.read_text())
    output = generate(db)
    if args.binary:
        args.binary.parent.mkdir(parents=True, exist_ok=True)
        args.binary.write_bytes(binary(db))
    if args.source != ROOT/'data/save-cheats.json':
        print('Custom console database exported; bundled fallback unchanged')
        return
    target = ROOT / 'src/save_cheat_db.h'
    if args.check:
        assert target.read_text() == output, 'Run python3 tools/build-save-cheats.py'
    else:
        target.write_text(output)
    print('Save cheats: shared database validated; C tables ' + ('current' if args.check else 'generated'))

if __name__ == '__main__':
    main()
