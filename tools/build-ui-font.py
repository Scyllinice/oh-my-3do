#!/usr/bin/env python3
"""Regenerate the OM3DO UI bitmap font from the Ark Pixel font.

Usage: build-ui-font.py ARK_10PX_TTF ARK_12PX_TTF

Ark Pixel is drawn pixel by pixel at 10 and 12 px, so at those sizes every
glyph is crisp without the stair-steps of a rasterized outline font. Use the
proportional Latin TTFs (ark-pixel-10px-proportional-latin.ttf and
ark-pixel-12px-proportional-latin.ttf) from
https://github.com/TakWolf/ark-pixel-font/releases (built from 2026.10.16).
The 4-bit coverage format is kept; coverage is always 0 or 15."""
import hashlib
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parent.parent
if len(sys.argv)!=3: sys.exit(__doc__)
ark10,ark12=Path(sys.argv[1]),Path(sys.argv[2])
# (font, size, cell height) for normal, small, large and heading; heights match
# ui_font_height(). The heading is the 10 px design doubled, which needs all 20
# rows of the glyph cell.
styles=((ark12,12,15),(ark10,10,12),(ark12,12,17),(ark10,20,20))
ascii=''.join(chr(code) for code in range(32,127))
widths=[]; bitmaps=[]
for path,size,height in styles:
    font=ImageFont.truetype(str(path),size)
    top=min(font.getbbox(char,anchor='ls')[1] for char in ascii[1:])
    bottom=max(font.getbbox(char,anchor='ls')[3] for char in ascii[1:])
    if bottom-top>height: sys.exit(f'{path.name} at {size} px is taller than {height} rows')
    baseline=-top+(height-(bottom-top))//2
    advances=[]; glyphs=[]
    for char in ascii:
        image=Image.new('L',(32,32)); draw=ImageDraw.Draw(image); draw.fontmode='1'
        draw.text((0,baseline),char,font=font,fill=255,anchor='ls')
        box=image.getbbox()
        if box and box[2]>16: sys.exit(f'{char!r} at {size} px is wider than the 16-pixel cell')
        advances.append(round(font.getlength(char)))
        cell=lambda x,y: 15 if image.getpixel((x,y)) else 0
        glyph=[]
        for y in range(20):
            for x in range(0,16,2):
                glyph.append((cell(x,y)<<4)|cell(x+1,y))
        glyphs.append(glyph)
    widths.append(advances); bitmaps.append(glyphs)
output=['/* Generated by tools/build-ui-font.py; OM3DO UI, derived from Ark Pixel.',
        ' * 10 px source SHA256: '+hashlib.sha256(ark10.read_bytes()).hexdigest(),
        ' * 12 px source SHA256: '+hashlib.sha256(ark12.read_bytes()).hexdigest(),
        ' * See vendor/fonts/ark-pixel-OFL.txt for the font license. */',
        'static const unsigned char ui_advances[%d][95] = {'%len(styles)]
for advances in widths: output.append('    {'+','.join(map(str,advances))+'},')
output+=['};','static const unsigned char ui_glyphs[%d][95][160] = {'%len(styles)]
for glyphs in bitmaps:
    output.append('    {')
    for glyph in glyphs: output.append('        {'+','.join(f'0x{n:02x}' for n in glyph)+'},')
    output.append('    },')
output+=['};']
(ROOT/'src/ui_font_data.h').write_text('\n'.join(output)+'\n')
