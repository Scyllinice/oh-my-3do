#!/usr/bin/env python3
"""Regenerate the OM3DO UI antialiased bitmap font from local DejaVu Sans TTFs."""
import hashlib
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parent.parent
source=Path(sys.argv[1]) if len(sys.argv)>1 else Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')
bold=source.with_name(source.stem+'-Bold.ttf')
styles=((12,11,15),(10,9,12),(14,13,17),(16,15,19))
widths=[]; bitmaps=[]
for index,(size,baseline,height) in enumerate(styles):
    font=ImageFont.truetype(str(bold if index==1 else source),size)
    advances=[]; glyphs=[]
    for code in range(32,127):
        char=chr(code); image=Image.new('L',(16,20)); draw=ImageDraw.Draw(image)
        draw.text((0,baseline),char,font=font,fill=255,anchor='ls')
        advance=max(2,round(font.getlength(char)))
        advances.append(advance)
        # Four-bit coverage retains smooth edges instead of thresholding to 1 bit.
        glyph=[]
        for y in range(20):
            for x in range(0,16,2):
                a=(image.getpixel((x,y))*15+127)//255
                b=(image.getpixel((x+1,y))*15+127)//255
                glyph.append((a<<4)|b)
        glyphs.append(glyph)
    widths.append(advances); bitmaps.append(glyphs)
output=['/* Generated by tools/build-ui-font.py; OM3DO UI, derived from DejaVu Sans.',
        ' * Regular source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
        ' * Bold source SHA256: '+hashlib.sha256(bold.read_bytes()).hexdigest(),
        ' * See vendor/fonts/LICENSE.txt for the font license. */',
        'static const unsigned char ui_advances[4][95] = {']
for advances in widths: output.append('    {'+','.join(map(str,advances))+'},')
output+=['};','static const unsigned char ui_glyphs[4][95][160] = {']
for glyphs in bitmaps:
    output.append('    {')
    for glyph in glyphs: output.append('        {'+','.join(f'0x{n:02x}' for n in glyph)+'},')
    output.append('    },')
output+=['};']
(ROOT/'src/ui_font_data.h').write_text('\n'.join(output)+'\n')
