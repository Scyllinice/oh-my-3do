#!/usr/bin/env python3
"""Regenerate the small OM3DO UI bitmap font from a local DejaVu Sans TTF."""
import hashlib
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parent.parent
source=Path(sys.argv[1]) if len(sys.argv)>1 else Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')
styles=((10,9,12),(8,8,10),(12,11,15),(16,15,19))
widths=[]; bitmaps=[]
for size,baseline,height in styles:
    font=ImageFont.truetype(str(source),size)
    advances=[]; glyphs=[]
    for code in range(32,127):
        char=chr(code); image=Image.new('L',(16,20)); draw=ImageDraw.Draw(image)
        draw.text((0,baseline),char,font=font,fill=255,anchor='ls')
        advance=max(2,round(font.getlength(char)))
        advances.append(advance)
        glyphs.append([sum((1<<(15-x)) for x in range(16) if image.getpixel((x,y))>=96) for y in range(20)])
    widths.append(advances); bitmaps.append(glyphs)
output=['/* Generated by tools/build-ui-font.py; OM3DO UI, derived from DejaVu Sans.',
        ' * Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
        ' * See vendor/fonts/LICENSE.txt for the font license. */',
        'static const unsigned char ui_advances[4][95] = {']
for advances in widths: output.append('    {'+','.join(map(str,advances))+'},')
output+=['};','static const unsigned short ui_glyphs[4][95][20] = {']
for glyphs in bitmaps:
    output.append('    {')
    for glyph in glyphs: output.append('        {'+','.join(f'0x{n:04x}' for n in glyph)+'},')
    output.append('    },')
output+=['};']
(ROOT/'src/ui_font_data.h').write_text('\n'.join(output)+'\n')
