#!/usr/bin/env python3
"""Generate the small built-in save-name fallback from the shared TSV.

data/save-names.txt lists save file names and the games they belong to,
one per line: a key, a tab, and the game's title. The key is "=" followed
by an exact file name, or "*" followed by a file name prefix. This writes
them as a C table (src/save_name_db.h) that the menu uses when a drive has
no save-names.txt of its own.

With --check, only checks the table is up to date.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The menu's limits: a key of at most 32 characters (with its "=" or "*")
# and a title shorter than 96 characters, both plain printable ASCII.
MAX_KEY_LENGTH = 32
MAX_TITLE_LENGTH = 95


def is_valid_row(key, title, seen):
    """Whether a row is well formed and its key is not already listed (in any case)."""
    printable = all(32 <= ord(character) < 127 for character in key + title)
    return (
        key[0] in "=*"
        and 1 < len(key) <= MAX_KEY_LENGTH
        and title
        and len(title) <= MAX_TITLE_LENGTH
        and printable
        and key.lower() not in seen
    )


def table_rows(lines):
    """The C table's rows: {name, title, is_prefix, 0} for each entry."""
    rows = []
    seen = set()
    for line in lines:
        if not line or line.startswith("#"):
            continue
        key, title = line.split("\t")
        if not is_valid_row(key, title, seen):
            raise SystemExit(f"Invalid/duplicate save-name row: {line}")
        seen.add(key.lower())
        name = json.dumps(key[1:])
        is_prefix = key[0] == "*"
        rows.append("    {%s,%s,%d,0}," % (name, json.dumps(title), is_prefix))
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    lines = (ROOT / "data/save-names.txt").read_text(encoding="ascii").splitlines()
    text = (
        "/* Generated by tools/build-save-names.py. */\n"
        "static const SaveNameEntry builtin_save_names[] = {\n"
        + "\n".join(table_rows(lines))
        + "\n};\n"
    )

    path = ROOT / "src/save_name_db.h"
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit("Run tools/build-save-names.py")
    else:
        path.write_text(text)


if __name__ == "__main__":
    main()
