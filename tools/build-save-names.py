#!/usr/bin/env python3
"""Generate the small built-in save-name fallback from the shared TSV."""
import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    rows, seen = [], set()
    for line in (root/'data/save-names.txt').read_text(encoding='ascii').splitlines():
        if not line or line.startswith('#'):
            continue
        key, title = line.split('\t')
        if not (key[0] in '=*' and 1 < len(key) <= 32 and title and len(title) < 96
                and all(32 <= ord(c) < 127 for c in key+title) and key.lower() not in seen):
            raise SystemExit(f'Invalid/duplicate save-name row: {line}')
        seen.add(key.lower())
        rows.append('    {%s,%s,%d,0},' % (json.dumps(key[1:]), json.dumps(title), key[0] == '*'))
    text = ('/* Generated by tools/build-save-names.py. */\n'
            'static const SaveNameEntry builtin_save_names[] = {\n' + '\n'.join(rows) + '\n};\n')
    path = root/'src/save_name_db.h'
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('Run tools/build-save-names.py')
    else:
        path.write_text(text)


if __name__ == '__main__':
    main()
