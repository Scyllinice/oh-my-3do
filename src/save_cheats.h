/*
 * Known save layouts ("cheats"): for some games the menu knows where in a
 * save file values such as lives, money or level live, and can change them
 * safely, including fixing the save's checksum afterwards.
 *
 * Each known layout is a "profile". A profile only applies to a save that
 * matches it completely: the right file name and size, a signature value at
 * a fixed place, a correct checksum, and every known value within its
 * allowed range. Anything else is left to the raw hex editor.
 *
 * Profiles come from two places: tables compiled into the menu
 * (save_cheat_db.h, generated by tools/build-save-cheats.py), or a database
 * file the desktop app installs on the drive (.ohmy3do/save-cheats.3db),
 * which replaces the built-in tables when it loads.
 *
 * All offsets are positions in the save file, never memory addresses in a
 * running game. An edit that is rejected changes nothing.
 */
#ifndef OH3DO_SAVE_CHEATS_H
#define OH3DO_SAVE_CHEATS_H
#include "save_archive.h"

/*
 * One editable value in a save: `width` bytes (1, 2 or 4, big-endian) at
 * `offset`, of which the bits in `mask` (a single run of bits) hold the
 * value. For example a 4-bit counter in the high half of a byte has width 1
 * and mask 0xf0.
 */
typedef struct SaveCheatField {
    const char *label; /* shown on screen, e.g. "Lives" */
    size_t offset;
    unsigned long min, max; /* the values the game accepts */
    size_t width;
    unsigned long mask;
} SaveCheatField;

/* An extra value a preset sets along with its main one. */
typedef struct SaveCheatChange {
    size_t field; /* index into the profile's fields */
    unsigned long value;
} SaveCheatChange;

/* A named shortcut, such as "Max lives": sets one field, and optionally others. */
typedef struct SaveCheatPreset {
    const char *label;
    size_t field;
    unsigned long value;
    const SaveCheatChange *additional;
    size_t additional_count;
} SaveCheatPreset;

/* Everything known about one game's save layout. */
typedef struct SaveCheatProfile {
    const char *id;       /* unique identifier */
    const char *game;     /* game title, for display */
    const char *filename; /* the NVRAM file name it applies to */
    size_t size;          /* the save's exact size */
    /* A fixed value that identifies this layout: `signature_width` bytes
     * (1, 2 or 4) at `signature_offset`. */
    size_t signature_offset;
    unsigned long signature;
    /* With checksum_kind 1, the last four bytes (at checksum_offset) hold
     * checksum_seed plus every 32-bit big-endian word before them. With
     * checksum_kind 0 there is no checksum and checksum_offset is the size. */
    size_t checksum_offset;
    unsigned long checksum_seed;
    const SaveCheatField *fields;
    size_t field_count;
    const SaveCheatPreset *presets;
    size_t preset_count;
    size_t signature_width;
    int checksum_kind;
} SaveCheatProfile;

/* The profile that matches `entry` completely (see above), or NULL. */
const SaveCheatProfile *save_cheats_find(const SaveEntry *entry);

/* The current value of `field` in a save. */
unsigned long save_cheats_value(const SaveEntry *entry, const SaveCheatField *field);

/*
 * Sets field number `field` to `value` in the save (whose data must be
 * writable) and fixes its checksum. The save must match `profile` and the
 * value must be in range. Returns 0, or -1 without changing anything.
 */
int save_cheats_set(SaveEntry *entry, const SaveCheatProfile *profile, size_t field,
                    unsigned long value);

/* Applies preset number `preset`, as save_cheats_set does. Returns 0, or -1. */
int save_cheats_preset(SaveEntry *entry, const SaveCheatProfile *profile, size_t preset);

/* The largest database file the menu reads. */
#define SAVE_CHEAT_DB_MAX_BYTES 65536UL

/*
 * Installs a database read from the drive (`size` bytes, copied). Everything
 * in it is checked before any of it is used; if anything is wrong, the
 * profiles in use stay as they were. Returns 0, or -1.
 */
int save_cheats_load(const unsigned char *bytes, size_t size);

/* Drops a loaded database and goes back to the built-in profiles. */
void save_cheats_reset(void);

/* How many profiles are in use. */
size_t save_cheats_profile_count(void);

/* Whether the profiles in use came from the drive (1) or are built in (0). */
int save_cheats_external(void);
#endif
